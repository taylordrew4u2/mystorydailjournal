import SwiftUI
import SwiftData
import PhotosUI
import UniformTypeIdentifiers

/// The full entry experience for one day (§6), split into two panels:
/// **Diary** holds the finished, woven entry; **Notes** is a persistent
/// scratchpad (plus guided questions) whose contents get woven into the
/// diary every time you switch back — the notes themselves never disappear.
struct EntryView: View {
    let date: Date

    private enum EntryPanel: String, CaseIterable {
        case diary = "Diary"
        case notes = "Notes"
    }

    @EnvironmentObject private var settings: SettingsStore
    @Environment(\.modelContext) private var context

    @State private var record: DayRecord?
    @State private var panel: EntryPanel = .diary
    @State private var notesSnapshot = ""
    @State private var isGeneratingPastDay = false
    @State private var showRefinement = false
    @State private var showAddNote = false
    @State private var noteText = ""
    @State private var showPhotoPicker = false
    @State private var pickedPhotos: [PhotosPickerItem] = []
    @State private var showFileImporter = false
    @State private var showShareSheet = false
    @State private var showCorrection = false

    var body: some View {
        Group {
            if let record {
                content(for: record)
            } else {
                ProgressView()
            }
        }
        .navigationTitle(Text(date, format: .dateTime.month(.wide).day().year()))
        .navigationBarTitleDisplayMode(.inline)
        .toolbar {
            ToolbarItem(placement: .navigationBarTrailing) {
                Menu {
                    Button("Add a note", systemImage: "note.text") { showAddNote = true }
                    Button("Add photos", systemImage: "photo.on.rectangle") { showPhotoPicker = true }
                    Button("Attach a file", systemImage: "doc") { showFileImporter = true }

                    Divider()

                    Button("Share", systemImage: "square.and.arrow.up") {
                        showShareSheet = true
                    }
                    .disabled(record?.bodyText.isEmpty ?? true)

                    Button("Tell it what it got wrong", systemImage: "text.badge.checkmark") {
                        showCorrection = true
                    }
                    .disabled(isGeneratingPastDay || record == nil)

                    Button("Rewrite with latest details", systemImage: "arrow.clockwise") {
                        regenerateDay(force: true, preserveText: true)
                    }
                    .disabled(isGeneratingPastDay || record == nil)
                } label: {
                    Image(systemName: "ellipsis.circle")
                }
            }
        }
        .alert("Add a note to this day", isPresented: $showAddNote) {
            TextField("What should this day remember?", text: $noteText)
            Button("Cancel", role: .cancel) { noteText = "" }
            Button("Add") { addNote() }
        } message: {
            Text("Notes are woven into the day's story when it's regenerated.")
        }
        .photosPicker(isPresented: $showPhotoPicker, selection: $pickedPhotos, matching: .images, photoLibrary: .shared())
        .onChange(of: pickedPhotos) { _, items in
            guard !items.isEmpty else { return }
            addPhotos(items)
            pickedPhotos = []
        }
        .fileImporter(isPresented: $showFileImporter, allowedContentTypes: [.item], allowsMultipleSelection: true) { result in
            addFiles(result)
        }
        .task {
            loadRecord()
            await capturePreciseLocationIfNeeded()
        }
    }

    /// The "on-demand fix at a meaningful moment" from §3 — writing to
    /// today, specifically, rather than continuous tracking. A no-op for
    /// any other day, or when precise location isn't turned on.
    private func capturePreciseLocationIfNeeded() async {
        guard DateUtilities.startOfDay(for: date) == DateUtilities.startOfDay(for: .now) else { return }
        guard settings.locationEnabled, settings.fullAccuracyLocationEnabled else { return }
        await LocationVisitMonitor.shared.captureExactLocation(for: date)
    }

    @ViewBuilder
    private func content(for record: DayRecord) -> some View {
        VStack(spacing: 0) {
            if record.source == .autoGenerated, panel == .diary {
                AutoDayBanner()
                    .padding(.top, 8)
            }

            if canGeneratePastDay(record) {
                Button {
                    regenerateDay()
                } label: {
                    if isGeneratingPastDay {
                        ProgressView()
                    } else {
                        Label("Generate this day from your phone's data", systemImage: "sparkles")
                            .font(.footnote)
                    }
                }
                .disabled(isGeneratingPastDay)
                .padding(.top, 8)
            }

            DayMetadataStrip(record: record)
                .padding(.top, 8)

            TagChipRow(date: date)
                .padding(.top, 12)

            PersonChipsSection(record: record)
                .padding(.top, 8)

            if DateUtilities.startOfDay(for: date) == DateUtilities.startOfDay(for: .now) {
                ScreenTimePanel()
                    .padding(.top, 8)
            }

            Picker("Panel", selection: $panel) {
                ForEach(EntryPanel.allCases, id: \.self) { Text($0.rawValue).tag($0) }
            }
            .pickerStyle(.segmented)
            .padding()

            switch panel {
            case .diary:
                if isGeneratingPastDay {
                    Spacer()
                    ProgressView("Weaving your day together…")
                    Spacer()
                } else {
                    FreeformEntryView(record: record)
                }
            case .notes:
                notesPanel(for: record)
            }
        }
        // The two-panel contract: entering Notes snapshots what's there;
        // leaving Notes saves and — if anything changed — weaves the whole
        // scratchpad into the diary, so switching back shows everything
        // you wrote already worked into the entry.
        .onChange(of: panel) { oldValue, newValue in
            if newValue == .notes {
                notesSnapshot = record.notesText
            } else if oldValue == .notes {
                try? context.save()
                weaveNotesIfChanged(record)
            }
        }
        .sheet(isPresented: $showShareSheet) {
            EntryShareSheet(record: record)
        }
        // Saying why the last attempt was wrong is what makes the next one
        // right — here, and on every day after this one.
        .sheet(isPresented: $showCorrection) {
            EntryCorrectionSheet(record: record) {
                regenerateDay(force: true, preserveText: record.isUserWritten)
            }
        }
        .sheet(isPresented: $showRefinement) {
            NavigationStack {
                GuidedEntryView(
                    record: record,
                    questions: guidedQuestions(for: record),
                    baseText: record.bodyText
                ) {
                    // The guided flow has already woven its answers into the
                    // diary and logged them into the notes; re-snapshotting
                    // stops the panel switch below from rebuilding the day a
                    // second time over the same material.
                    notesSnapshot = record.notesText
                    showRefinement = false
                    panel = .diary
                }
                .navigationTitle("Guided questions")
                .navigationBarTitleDisplayMode(.inline)
            }
        }
    }

    /// The scratchpad half of the two-panel layout: write as much as you
    /// want, it never disappears and is never consumed — switching back to
    /// Diary weaves everything here into the entry. Guided questions live
    /// here too, for days you'd rather be prompted.
    @ViewBuilder
    private func notesPanel(for record: DayRecord) -> some View {
        @Bindable var record = record
        VStack(alignment: .leading, spacing: 10) {
            Text("Jot anything — it stays here, and switching back to Diary weaves it into the entry.")
                .font(.footnote)
                .foregroundStyle(.secondary)

            TextEditor(text: $record.notesText)
                .font(.body)
                .scrollContentBackground(.hidden)
                .padding(8)
                .background(Color.secondary.opacity(0.06))
                .clipShape(RoundedRectangle(cornerRadius: 12))

            Button {
                showRefinement = true
            } label: {
                Label(promptButtonTitle(for: record), systemImage: "text.badge.checkmark")
                    .font(.footnote)
            }
        }
        .padding()
    }

    /// Weaves the scratchpad into the diary when its contents changed while
    /// the Notes panel was open. Days with the user's own diary text keep
    /// those words — force-regeneration pins them before rebuilding.
    private func weaveNotesIfChanged(_ record: DayRecord) {
        let current = record.notesText.trimmingCharacters(in: .whitespacesAndNewlines)
        let previous = notesSnapshot.trimmingCharacters(in: .whitespacesAndNewlines)
        guard current != previous, !current.isEmpty else { return }

        if record.isUserWritten {
            regenerateDay(force: true, preserveText: true)
        } else {
            regenerateDay()
        }
    }

    /// A past day with nothing on it yet — today is excluded because the
    /// digest for today is composed after the day ends, and user-written
    /// days must never be regenerated over.
    private func canGeneratePastDay(_ record: DayRecord) -> Bool {
        DateUtilities.startOfDay(for: date) < DateUtilities.startOfDay(for: .now)
            && !record.isUserWritten
            && record.bodyText.isEmpty
    }

    /// Signal-specific prompts when the day has material to ask about
    /// (places, events, the photos themselves and the faces in them), with
    /// the user's chosen prompt set held in reserve afterwards. A quiet
    /// day still gets the chosen prompt set, and an active day never runs
    /// out the moment the phone-derived questions are answered.
    private func guidedQuestions(for record: DayRecord) -> [GuidedQuestion] {
        let signalQuestions = GuidedQuestionBuilder.questions(
            signals: record.signals ?? [],
            timeZoneIdentifier: record.timeZoneIdentifier
        )
        let savedPrompts = GuidedQuestion.from(settings.activeQuestionSet)
        let learnedPrompts = learnedQuestions()
        var seen = Set<String>()
        return (signalQuestions + learnedPrompts + savedPrompts).filter { question in
            seen.insert(question.text.normalizedPromptText).inserted
        }
    }

    private func promptButtonTitle(for record: DayRecord) -> String {
        let context = GuidedQuestionBuilder.contextSummary(for: record.signals ?? [])
        guard context.isActive else { return "Answer a few prompts" }
        return "Answer prompts about \(context.shortDescription)"
    }

    private func learnedQuestions(limit: Int = 3) -> [GuidedQuestion] {
        var descriptor = FetchDescriptor<ProfileFact>(
            predicate: #Predicate { !$0.isMuted },
            sortBy: [
                SortDescriptor(\.lastObserved, order: .reverse),
            ]
        )
        descriptor.fetchLimit = 12

        let facts = (try? context.fetch(descriptor)) ?? []
        let ranked = facts.sorted {
            if $0.isPinned != $1.isPinned { return $0.isPinned }
            if $0.observationCount != $1.observationCount { return $0.observationCount > $1.observationCount }
            return $0.lastObserved > $1.lastObserved
        }
        return ranked.compactMap(Self.learnedQuestion).prefix(limit).map { $0 }
    }

    private static func learnedQuestion(for fact: ProfileFact) -> GuidedQuestion? {
        switch fact.kind {
        case .place:
            return GuidedQuestion(
                id: "learned.place.\(fact.id.uuidString)",
                text: "You have written about \(fact.subject) before. Did it matter today?",
                subject: .open,
                feelingPrompt: "How did that place sit with you today?"
            )
        case .rhythm:
            return GuidedQuestion(
                id: "learned.rhythm.\(fact.id.uuidString)",
                text: "This looks close to one of your usual rhythms: \(fact.subject). Did today follow it or break from it?",
                subject: .open,
                feelingPrompt: "How did that rhythm feel today?"
            )
        case .theme:
            return GuidedQuestion(
                id: "learned.theme.\(fact.id.uuidString)",
                text: "You often come back to \(fact.subject). Was that part of today?",
                subject: .open,
                feelingPrompt: "How do you feel about it now?"
            )
        case .person, .voice, .correction:
            return nil
        }
    }

    /// Generates or regenerates this day's digest on demand: first-time
    /// generation for an empty past day, or a re-run on an auto-generated
    /// day so newly attached notes/photos/files and the latest composer
    /// detail get folded in. Never touches user-written days (the engine
    /// refuses those). Runs on this view's own context — the engine
    /// rewrites the exact record on screen, so the new text appears the
    /// moment it's composed.
    private func regenerateDay(force: Bool = false, preserveText: Bool = true) {
        guard !isGeneratingPastDay else { return }
        isGeneratingPastDay = true
        try? context.save()

        Task {
            if force {
                await DigestEngine.forceRegenerate(for: date, preservingText: preserveText, in: context)
            } else {
                await DigestEngine.generateDigestIfNeeded(for: date, in: context)
            }
            record = nil
            loadRecord()
            isGeneratingPastDay = false
        }
    }

    // MARK: - Attachments

    /// Pins signals to this day in one batch, then — on a day the user
    /// hasn't written themselves — regenerates once so the additions show
    /// up in the story right away. On user-written days the attachments are
    /// stored but the text is never touched.
    private func attach(_ payloads: [AttachmentPayload]) {
        guard let record, !payloads.isEmpty else { return }
        for payload in payloads {
            let signal = DaySignal(kind: .attachment, timestamp: date)
            signal.setPayload(payload)
            signal.dayRecord = record
            context.insert(signal)
            if record.signals == nil { record.signals = [] }
            record.signals?.append(signal)
        }
        try? context.save()

        if !record.isUserWritten {
            regenerateDay()
        }
    }

    private func addNote() {
        let trimmed = noteText.trimmingCharacters(in: .whitespacesAndNewlines)
        noteText = ""
        guard !trimmed.isEmpty else { return }
        attach([AttachmentPayload(kind: .note, text: trimmed)])
    }

    private func addPhotos(_ items: [PhotosPickerItem]) {
        attach(items.map { AttachmentPayload(kind: .photo, assetLocalIdentifier: $0.itemIdentifier) })
    }

    /// Stores file *names* only — never contents (§10).
    private func addFiles(_ result: Result<[URL], Error>) {
        guard case .success(let urls) = result else { return }
        attach(urls.map { AttachmentPayload(kind: .file, fileName: $0.lastPathComponent) })
    }

    private func loadRecord() {
        guard record == nil else { return }
        record = DayRecordRepository.record(for: date, in: context)
    }
}

private extension String {
    var normalizedPromptText: String {
        trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
    }
}

/// Shown on an auto-generated day so the user knows this isn't their own
/// writing yet — disappears the moment they start typing, since the entry
/// views flip `source` to `.converted` on the first edit (§10, §14).
private struct AutoDayBanner: View {
    var body: some View {
        HStack(spacing: 8) {
            Image(systemName: "sparkles")
            Text("Written automatically from what your phone noticed. Start typing to make it yours.")
                .font(.footnote)
        }
        .foregroundStyle(.secondary)
        .padding(.horizontal)
        .frame(maxWidth: .infinity, alignment: .leading)
    }
}
